"""sag.py KIND SAG TEST: the UH-20 power section (long-tailed pair, LM3886, feedback, Presence 5) on its real supply, with the Sag
element either the original rheostat (KIND=rheo) or the active rheostat (KIND=active), driven at the Master's output by
  TEST=step:  110 Hz at 0.3, 1, 2 and 4 V peak, 0.3 s each (the last two clip the LM3886 hard), or
  TEST=pluck: four plucked low-E notes (82.4 Hz and three harmonics, 4 V, 0.5 ms attack, 0.25 s decay, muted over the last 20 ms) 0.4 s apart.
The signal starts at 0.8 s, after the supply has come up. Writes sag_KIND_SAG_TEST.txt: time, v(rp), v(rn), speaker, + rail charging
current, element voltage (+ rail), - rail charging current, element voltage (- rail).
sag.py compare: runs both kinds at Sag 0, 3, 7, 10 for both tests and prints rail droop and the differences.
sag.py startup: power-up with no signal, active rheostat at Sag 3 and 10, with and without the primary soft-start: the pass
FET's peak power and the energy it takes."""
import os, sys, subprocess, math
H = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, H)
import rhythm

SIG = {"step": "V=(time<0.8 ? 0 : time<1.1 ? 0.3 : time<1.4 ? 1 : time<1.7 ? 2 : 4)*sin(2*pi*110*time)",
       "pluck": "V=time<0.8 ? 0 : 4*min(TAU/0.5m,1)*min((0.4-TAU)/20m,1)*exp(-TAU/0.25)*(sin(2*pi*82.4*TAU)+0.5*sin(2*pi*164.8*TAU)+0.33*sin(2*pi*247.2*TAU)"
                "+0.25*sin(2*pi*329.6*TAU))".replace("TAU", "(time-0.8-0.4*floor((time-0.8)/0.4))")}
TEND = {"step": 2.0, "pluck": 2.39}


def run(kind, sag, test):
    out = os.path.abspath(f"sag_{kind}_{sag:g}_{test}.txt"); cir = out[:-4] + ".cir"
    kn = dict(supply=kind, sag=sag)
    open(cir, "w").write(f"""* UH-20 power section on its real supply, Sag element = {kind} (generated by sag.py)
.include {H}/j201.lib
VP vp 0 DC 15
VN vn 0 DC -15
BSIG mv 0 {SIG[test]}
C5 mv lg1 1u
RL1 lg1 0 100k
{rhythm.power(0.5, 0, kn)}.options method=gear reltol=1e-4
.tran 2.6u {TEND[test]} 0.7 2.6u
.control
run
linearize
wrdata {out} v(rp) v(rn) v(out) i(vap) v(bp,rp) i(van) v(rn,bn)
.endc
.end
""")
    subprocess.run(["ngspice", "-b", cir], capture_output=True, check=True)
    rows = [list(map(float, l.split())) for l in open(out)]   # linearized onto a 2.6 us grid
    return [(r[0], r[1::2]) for r in rows]   # (time, [v(rp), v(rn), speaker, i+, v+, i-, v-])


def compare():
    from concurrent.futures import ThreadPoolExecutor
    jobs = [(k, s, t) for t in ("step", "pluck") for s in (0, 3, 7, 10) for k in ("rheo", "active")]
    with ThreadPoolExecutor(os.cpu_count()) as ex: res = dict(zip(jobs, ex.map(lambda j: run(*j), jobs)))
    for t in ("step", "pluck"):
        print(f"\n{t}: rails at rest -> lowest under load (V); active against rheostat")
        print("Sag | +rail rheo     | +rail active   | -rail rheo       | -rail active     | max rail diff | speaker residual | speaker max diff | + element W, avg over the test / peak")
        for s in (0, 3, 7, 10):
            A, B = res[("rheo", s, t)], res[("active", s, t)]; n = min(len(A), len(B))
            rest = [r for tt, r in A[:n] if tt < 0.8]; restb = [r for tt, r in B[:n] if tt < 0.8]
            dr = max(max(abs(A[i][1][0] - B[i][1][0]), abs(A[i][1][1] - B[i][1][1])) for i in range(n))
            sig = [i for i in range(n) if A[i][0] >= 0.8]
            so = [A[i][1][2] for i in sig]; d = [B[i][1][2] - A[i][1][2] for i in sig]
            rms = lambda v: math.sqrt(sum(x * x for x in v) / len(v))
            pw = [B[i][1][3] * B[i][1][4] for i in sig]   # + rail element (the - rail mirrors it)
            mean = lambda v: sum(v) / len(v)
            print(f"{s:3d} | {mean([r[0] for r in rest]):5.2f} -> {min(r[1][0] for r in A[:n]):5.2f} | "
                  f"{mean([r[0] for r in restb]):5.2f} -> {min(r[1][0] for r in B[:n]):5.2f} | "
                  f"{mean([r[1] for r in rest]):6.2f} -> {max(r[1][1] for r in A[:n]):6.2f} | "
                  f"{mean([r[1] for r in restb]):6.2f} -> {max(r[1][1] for r in B[:n]):6.2f} | {1000 * dr:8.1f} mV | "
                  f"{20 * math.log10(rms(d) / rms(so) + 1e-30):10.1f} dB | {1000 * max(map(abs, d)):11.1f} mV | {mean(pw):5.2f} / {max(pw):5.1f}")


def startup():
    def one(sag, soft):
        out = os.path.abspath(f"sag_startup_{sag:g}_{soft}.txt"); cir = out[:-4] + ".cir"
        open(cir, "w").write(f"""* UH-20 power section, power-up (generated by sag.py)
.include {H}/j201.lib
VP vp 0 DC 15
VN vn 0 DC -15
VSIG mv 0 DC 0
C5 mv lg1 1u
RL1 lg1 0 100k
{rhythm.power(0.5, 0, dict(supply="active", sag=sag, soft=soft))}.options method=gear reltol=1e-4
.tran 2.6u 0.8 0 2.6u
.control
run
wrdata {out} v(xp,rp) i(vap) v(rp)
.endc
.end
""")
        subprocess.run(["ngspice", "-b", cir], capture_output=True, check=True)
        r = [list(map(float, l.split())) for l in open(out)]
        p = [(x[0], x[1] * x[3]) for x in r]; e = sum((p[k][0] - p[k - 1][0]) * p[k][1] for k in range(1, len(p)))
        pk = max(p, key=lambda q: q[1]); k = [x for x in r if x[0] == pk[0]][0]
        return f"Sag {sag:2g}, soft-start {'on ' if soft else 'off'}: FET peak {pk[1]:5.0f} W ({k[1]:4.1f} V, {k[3]:4.1f} A at {1000 * pk[0]:4.1f} ms), {e:4.2f} J in all; rail {r[-1][5]:5.2f} V at 0.8 s"
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(4) as ex:
        for line in ex.map(lambda j: one(*j), [(s, f) for s in (3, 10) for f in (0, 1)]): print(line)


if __name__ == "__main__":
    if sys.argv[1] == "compare": compare()
    elif sys.argv[1] == "startup": startup()
    else: print(len(run(sys.argv[1], float(sys.argv[2]), sys.argv[3])), "rows")
