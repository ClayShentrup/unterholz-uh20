"""Write and run the UH-20 RHYTHM channel + power section as an ngspice netlist (J201 vendor model, LEDs, Mark III stack, J201
long-tailed pair, LM3886 as a gain block limited at fixed rails, feedback with Presence). Usage: rhythm.py AMP JUBILEE [k=v...]"""
import sys, subprocess, os, math
H = os.path.dirname(os.path.abspath(__file__))
def taperA(x): return 0.2 * x if x <= 0.5 else 0.1 + 1.8 * (x - 0.5)
def netlist(amp, kn, out):
    t = min(max(kn["treble"] / 10, 0.0004), 0.9996); b = max(taperA(kn["bass"] / 10), 0.0004); m = max(kn["middle"] / 10, 0.004)
    vv = min(max(taperA(kn["volume"] / 10), 0.0005), 0.9995); ma = min(max(taperA(kn["master"] / 10), 0.0005), 0.9995)
    jub = kn["jubilee"]; jon = jub >= 0.05; rj = 22 + 47e3 * taperA(1 - jub / 10); rg = 220 + 100e3 * taperA(1 - jub / 10)
    pres = min(max(kn["presence"] / 10, 0), 1); rail = 31.1 - 0.9 - 0.05 * 0.3 * 3 - 3.0
    VT = 0.025852; isled = 0.01 / math.exp(1.8 / (2 * VT))
    return f"""* UH-20 RHYTHM + power section (generated by rhythm.py)
.include {H}/j201.lib
.model LED D(IS={isled:.6e} N=2)
VDD dd 0 DC 18
VP vp 0 DC 15
VN vn 0 DC -15
VIN in 0 SIN(0 {amp} 220)
* Q1: 1k stopper, 1M leak; source 3.3k (|| Jubilee gang A: rg + 10u) then 1.5k || 0.68u
RIN in g1 1k
RLK g1 0 1Meg
J1 d1 g1 s1 J201
RD1 dd d1 68k
RS1 s1 m1 3.3k
{"RG s1 jj " + f"{rg:.6g}" + chr(10) + "CG jj m1 10u" if jon else ""}
RS1B m1 0 1.5k
CS1 m1 0 0.68u
* drain -> rail-to-rail follower -> 6.8k (68k/10) -> 470 -> A -> Mark III stack (every R /10, every C x10); A -> 4.7u -> Clip gang B -> LEDs
BBUF1 b1 0 V=max(min(V(d1),17.98),0.02)
RTH1 b1 d1b 6.8k
R47 d1b a 470
{("CLD a la 4.7u" + chr(10) + "RBL la 0 100k" + chr(10) + "RJ la l " + f"{rj:.6g}" + chr(10) + "DL1 l 0 LED" + chr(10) + "DL2 0 l2 LED" + chr(10) + "DL3 l2 l LED") if jon else ""}
CT a tt 2.5n
RT1 tt w {25e3*(1-t):.6g}
RT2 w tb {25e3*t:.6g}
RSL a x 10k
CB x tb 1u
RB tb mt {25e3*b:.6g}
CM x mt 0.47u
RM mt 0 {2.5e3*m:.6g}
RV1 w vw {100e3*(1-vv):.6g}
RV2 vw 0 {100e3*vv:.6g}
C2 vw g2 220n
RG2 g2 0 100k
* Q2: 47k / 2.2k || 22u -> 22n -> 100k / 6.8k
J2 d2 g2 s2 J201
RD2 dd d2 47k
RS2 s2 0 2.2k
CS2 s2 0 22u
C3 d2 a3 22n
R3 a3 g3 100k
R3B g3 0 6.8k
* Q3: 47k / 2.2k || 22u -> 100n -> 47k -> Master 1M log -> 0.1u -> LTP gate (1M)
J3 d3 g3 s3 J201
RD3 dd d3 47k
RS3 s3 0 2.2k
CS3 s3 0 22u
BBUF3 b3 0 V=max(min(V(d3),17.98),0.02)
RTH3 b3 d3b 4.7k
C4 d3b a4 1u
R4 a4 mw 4.7k
RM1 mw mv {100e3*(1-ma):.6g}
RM2 mv 0 {100e3*ma:.6g}
C5 mv lg1 1u
RL1 lg1 0 100k
* long-tailed pair, compensation, coupling into the LM3886 (gain 1 + 22k/5.6k, limited at the rails)
JA pa lg1 tail J201
JB pb lg2 tail J201
RDA vp pa 22k
RDB vp pb 22k
RTL tail vn 30k
CCMP pb 0 220p
C6 pb pin 1u
RPIN pin 0 47k
BOUT out 0 V=max(min({1+22/5.6}*V(pin),{rail}),-{rail})
RLOAD out 0 8
* feedback: 100k to the pair's second gate, 4.7k down; Presence: 0.1u + 5k pot
RNF out lg2 100k
RFB lg2 0 4.7k
CPR lg2 pn 0.1u
RPR pn 0 {5000*(1-pres)+47:.6g}
.tran 2.6u 0.5 0.3 2.6u
.control
run
wrdata {out} v(d1) v(d3) v(pb) v(out)
.endc
.end
"""
if __name__ == "__main__":
    amp = float(sys.argv[1]); kn = dict(volume=5, treble=3, middle=7, bass=5, presence=5, jubilee=float(sys.argv[2]), master=6.5)
    for a in sys.argv[3:]: k, v = a.split("="); kn[k] = float(v)
    out = os.path.abspath(f"rhythm_{amp}_{kn['jubilee']}.txt"); cir = out[:-4] + ".cir"; open(cir, "w").write(netlist(amp, kn, out))
    subprocess.run(["ngspice", "-b", cir], capture_output=True); print(out)
